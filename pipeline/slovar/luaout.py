"""Writes the dictionary as Lua files the addon loads (addon/Slovar/Data/).

Lemmas.lua: ns.Data.lemmas = { "display\\tlabel\\tgloss1\\tgloss2\\tgloss3", ... }   (index = lemma id)
Forms.lua:  ns.Data.forms[first letter] = "\\nform\\tid:tagset,tagset;id:tagset\\n..."  (one text block per letter)

The forms are kept as big strings instead of a Lua table with ~200k keys: a table that size costs tens of MB of
memory and load time in game, while a string block costs its byte size and is searched with one plain
string.find on hover.
"""
import os

from .kaikki import Lemma
from . import tags as T

HEADER = ("-- Generated by pipeline/build.py — do not edit.\n"
          "-- Dictionary data: English Wiktionary via kaikki.org (CC BY-SA 4.0); word forms of WoW names guessed with\n"
          "-- pymorphy3 / OpenCorpora (CC BY-SA). See README.md.\n")

GENDER = {"m": "masculine", "f": "feminine", "n": "neuter"}
POS_LABEL = {"noun": "noun", "name": "proper noun", "verb": "verb", "adj": "adjective", "adv": "adverb",
             "num": "numeral", "pron": "pronoun", "intj": "interjection", "det": "determiner",
             "prep": "preposition", "conj": "conjunction", "particle": "particle", "postp": "postposition",
             "contraction": "contraction"}


def label(lem: Lemma) -> str:
    if lem.pos == "participle":
        return " ".join(x for x in (lem.participle_kind, "participle of", lem.participle_of) if x)
    parts = [lem.participle_kind if lem.pos == "guess" else POS_LABEL.get(lem.pos, lem.pos)]
    if lem.pos in ("noun", "name", "guess"):
        if lem.plural_only:
            parts.append("plural only")
        elif lem.gender:
            parts.append(GENDER[lem.gender])
        if lem.animacy and lem.pos == "noun":
            parts.append(lem.animacy)
    if lem.pos == "verb" and lem.aspect:
        aspect = lem.aspect
        if lem.partner and aspect != "biaspectual":
            aspect += f" ({'impf.' if aspect == 'perfective' else 'pf.'} {lem.partner})"
        parts.append(aspect)
    return ", ".join(parts)


def _field(s: str) -> str:
    return " ".join(s.split()).replace("|", "/")  # "|" starts escape sequences in WoW text


def _lua_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def write(out_dir: str, lemma_rows: list[tuple[str, str, list[str]]], forms: dict[str, list[tuple[int, list[str]]]]):
    """lemma_rows[i] = (display, label, glosses) for lemma id i+1; forms: form -> [(lemma id, tagsets)]."""
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "Lemmas.lua"), "w", encoding="utf-8") as f:
        f.write(HEADER + "local _, ns = ...\nns.Data = ns.Data or {}\nns.Data.lemmas = {\n")
        for display, lab, glosses in lemma_rows:
            f.write(_lua_string("\t".join(_field(x) for x in [display, lab, *glosses[:3]])) + ",\n")
        f.write("}\n")
    buckets: dict[str, list[str]] = {}
    for form in sorted(forms):
        value = ";".join(f"{lid}:{','.join(ts)}" for lid, ts in forms[form])
        buckets.setdefault(form[0], []).append(f"{form}\t{value}")
    with open(os.path.join(out_dir, "Forms.lua"), "w", encoding="utf-8") as f:
        f.write(HEADER + "local _, ns = ...\nns.Data = ns.Data or {}\nlocal F = {}\nns.Data.forms = F\n")
        for letter in sorted(buckets):
            # Long string: the newline right after [=[ is dropped by Lua, the second one makes the block start
            # with "\n" so every entry can be found as "\n" .. form .. "\t".
            f.write(f'F["{letter}"] = [=[\n\n' + "\n".join(buckets[letter]) + "\n]=]\n")


def sort_tagsets(ts) -> list[str]:
    rank = {c: i for i, c in enumerate(T.ORDER)}
    return sorted(ts, key=lambda s: [rank[c] for c in s])
